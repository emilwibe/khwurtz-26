        <p>Trends come. Tendencies go.</p>

        <p>ometimes they circle back pretending to be new - wearing a thin, luxurious layer of semantic sheepskin, re-sheared, re-tanned, and rebranded.
We don't play that game. Not because we're above it but because
our workshop is so long that by the time you've walked from one end to the other, the tendency-cycle has already collapsed in on itself, been replaced by the next one, and is halfway to returning in its ironic form.
our space is physically longer than most design movements last. We will start the process at the northeast end, walk to the southern parts to finalize it, and by the time it has become, the “it-color” will have gone from green to rust to green again - but now in a matte finish.</p>
